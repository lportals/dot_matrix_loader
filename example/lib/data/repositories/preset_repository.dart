  /// Formats technical camelCase class names into human-readable spaced titles.
  static String formatPresetName(String className) {
    final buffer = StringBuffer();
    for (int i = 0; i < className.length; i++) {
      final char = className[i];
      if (i > 0 &&
          char == char.toUpperCase() &&
          className[i - 1] != className[i - 1].toUpperCase()) {
        buffer.write(' ');
      }
      buffer.write(char);
    }
    return buffer.toString();
  }
